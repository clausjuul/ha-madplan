function dish(
  id: string,
  name: string,
  ingredients: string[],
  prepMinutes: number,
  category: string,
  favorite: boolean,
  leftoverFriendly: boolean,
  freezerFriendly: boolean,
): Dish {
  return {
    id,
    name,
    ingredients,
    prepMinutes,
    category,
    favorite,
    leftoverFriendly,
    freezerFriendly,
    imageKey: id,
    instructions: DISH_INSTRUCTIONS[id] ?? [],
  };
}

